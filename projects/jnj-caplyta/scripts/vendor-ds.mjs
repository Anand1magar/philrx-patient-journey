// Vendors the shared design system into ./ds so this project stands alone.
//
// This brand ships to the client as its own repo, deployed separately — so it
// can't reach up to ../../components the way the base flow does. Instead it
// carries the slice of the design system it actually uses, and the @ds alias
// points at ./ds (see vite.config.js). Copy this folder anywhere and it builds.
//
// Run from the monorepo whenever the shared design system changes:
//   node scripts/vendor-ds.mjs
//
// It walks the @ds imports in src/, follows relative imports inside each copied
// file, and copies only the closure — not the whole 3.8MB design system.
import { readFileSync, writeFileSync, mkdirSync, cpSync, existsSync, rmSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PROJECT = resolve(HERE, '..');
const MONOREPO = resolve(PROJECT, '../..');
const DS_OUT = join(PROJECT, 'ds');

if (!existsSync(join(MONOREPO, 'components')) || !existsSync(join(MONOREPO, 'styles.css'))) {
  console.error(
    `No shared design system at ${MONOREPO}.\n` +
    'This script only runs inside the philrx-patient-journey monorepo — a\n' +
    'standalone copy already has everything it needs in ./ds.',
  );
  process.exit(1);
}

// Every file under src/ that could name an @ds path.
function sourceFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    if (e.isDirectory()) return sourceFiles(p);
    return /\.(jsx?|css)$/.test(e.name) ? [p] : [];
  });
}

const seeds = new Set();
for (const file of sourceFiles(join(PROJECT, 'src'))) {
  for (const m of readFileSync(file, 'utf8').matchAll(/@ds\/([A-Za-z0-9/_.-]+)/g)) {
    seeds.add(m[1]);
  }
}

// styles.css pulls the token files in via @import, and is imported by main.jsx.
seeds.add('styles.css');

const copied = new Set();
const queue = [...seeds];

while (queue.length) {
  const rel = queue.shift();
  if (copied.has(rel)) continue;
  const src = join(MONOREPO, rel);
  if (!existsSync(src)) {
    console.warn(`  ! missing in monorepo, skipped: ${rel}`);
    continue;
  }
  copied.add(rel);

  // Follow relative imports out of JS and CSS so transitive deps come along
  // (DeclineEnrollmentModal -> Modal -> Icon -> icon-data, styles.css -> tokens/*).
  if (/\.(jsx?|css)$/.test(rel)) {
    const text = readFileSync(src, 'utf8');
    const specs = [
      ...[...text.matchAll(/from\s+['"](\.[^'"]+)['"]/g)].map((m) => m[1]),
      ...[...text.matchAll(/import\s+['"](\.[^'"]+)['"]/g)].map((m) => m[1]),
      ...[...text.matchAll(/@import\s+(?:url\()?['"](\.[^'"]+)['"]/g)].map((m) => m[1]),
    ];
    for (const spec of specs) {
      queue.push(relative(MONOREPO, resolve(dirname(src), spec)));
    }
  }
}

rmSync(DS_OUT, { recursive: true, force: true });
let bytes = 0;
for (const rel of [...copied].sort()) {
  const from = join(MONOREPO, rel);
  const to = join(DS_OUT, rel);
  mkdirSync(dirname(to), { recursive: true });
  cpSync(from, to);
  bytes += statSync(from).size;
}

writeFileSync(
  join(DS_OUT, 'README.md'),
  `# ds/ — vendored design system\n\n` +
  `Generated by \`scripts/vendor-ds.mjs\`. **Do not edit by hand.**\n\n` +
  `This is the slice of the shared PhilRx design system that this brand imports,\n` +
  `copied in so the project builds on its own — it ships to the client as a\n` +
  `standalone repo and can't reach up to a monorepo root.\n\n` +
  `${copied.size} files. Re-run the script from inside the monorepo after any\n` +
  `shared design-system change; a standalone checkout needs nothing.\n\n` +
  `Brand-owned colors are NOT here — they live in \`src/brand-theme.css\`, which\n` +
  `loads after \`ds/styles.css\` and overrides it.\n`,
);

console.log(`Vendored ${copied.size} files (${(bytes / 1024).toFixed(0)} KB) into ds/`);
for (const rel of [...copied].sort()) console.log(`  ${rel}`);

// The autocomms tone reference travels with the project too — a standalone
// checkout needs to know which tone the SMS copy is written in and where the
// approved wording came from.
const REF_SRC = join(MONOREPO, 'reference/autocomms');
const REF_OUT = join(PROJECT, 'reference/autocomms');
if (existsSync(REF_SRC)) {
  rmSync(REF_OUT, { recursive: true, force: true });
  mkdirSync(dirname(REF_OUT), { recursive: true });
  cpSync(REF_SRC, REF_OUT, { recursive: true });
  console.log(`\nCopied reference/autocomms/ (${readdirSync(REF_OUT).length} files)`);
} else {
  console.warn('\n! reference/autocomms not found in the monorepo — skipped');
}
